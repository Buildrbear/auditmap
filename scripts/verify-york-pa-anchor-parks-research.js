#!/usr/bin/env node

const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const readJson = (file) => JSON.parse(fs.readFileSync(path.join(root, file), "utf8"));

const intake = readJson("data/research-intake/york-pa-anchor-parks-2026-09-04.json");
const campaign = readJson("data/york-pa-anchor-parks-research-completion-campaign.json");
const ledger = readJson("data/release-ledgers/york-pa-anchor-parks-2026-09-04.json");
const registry = readJson("data/generated/national-coverage-registry.json");
const packets = readJson("data/generated/national-work-packets.json");
const claims = readJson("data/national-work-packet-claims.json");
const queue = readJson("data/us-priority-enrichment-queue.json");
const sitemap = fs.readFileSync(path.join(root, "sitemap.xml"), "utf8");

assert.equal(intake.campaignId, "york-pa-anchor-parks-2026-09-04");
assert.equal(intake.contributionTier, "inventory");
assert.equal(intake.records.length, 8);
assert.equal(intake.selection.acceptedCount, 8);
assert.equal(campaign.places.length, 8);
assert.equal(ledger.summary.intakeRecords, 8);
assert.equal(ledger.summary.needsLaunchGuide, 8);
assert.equal(ledger.summary.generatedLocally, 0);
assert.equal(ledger.summary.deployed, 0);
assert.match(intake.sourcePolicy.imageRights, /aerial imagery is not an acceptable hero-photo substitute/i);
assert.equal(intake.releasePolicy.researchCompleteIsDeployable, false);

const names = new Set();
const slugs = new Set();
for (const record of intake.records) {
  assert.equal(record.state, "PA");
  assert.equal(record.country, "US");
  assert.equal(record.duplicate_status.startsWith("accepted-net-new-parent"), true);
  assert.match(record.contribution_status, /^qualified-inventory-parent/);
  assert.ok(Number.isFinite(record.latitude));
  assert.ok(Number.isFinite(record.longitude));
  assert.ok(record.latitude > 39.8 && record.latitude < 40.1);
  assert.ok(record.longitude > -76.85 && record.longitude < -76.3);
  assert.ok(record.address.length > 10);
  assert.ok(record.managing_agency.includes("York"));
  assert.match(record.official_source_url, /^https:\/\/(www\.)?(yorkcountypa\.gov|yorkcity\.org)\//);
  assert.ok(record.sources.length >= 2);
  assert.ok(record.sources.every((source) => source.checkedAt === "2026-09-04"));
  assert.ok(record.sources.every((source) => /^https:\/\//.test(source.url)));
  assert.ok(Array.isArray(record.candidate_subsites) && record.candidate_subsites.length >= 3);
  assert.ok(!names.has(record.name), `Duplicate York name: ${record.name}`);
  assert.ok(!slugs.has(record.slug), `Duplicate York slug: ${record.slug}`);
  names.add(record.name);
  slugs.add(record.slug);

  const route = `/us/pa/${record.city.toLowerCase().replace(/[^a-z0-9]+/g, "-")}/parks/${record.slug}`;
  assert.ok(!sitemap.includes(`<loc>https://www.auditmap.org${route}</loc>`), `${route} must remain unpublished`);
  assert.ok(!fs.existsSync(path.join(root, route.slice(1))), `${route} must not be generated by an inventory packet`);
}

const yorkRecords = registry.records.filter((record) =>
  record.state === "PA" && record.researchSources.some((source) => source.sourceId === intake.campaignId),
);
assert.equal(yorkRecords.length, 8);
assert.ok(yorkRecords.every((record) => ["research-only", "blocked-review"].includes(record.releaseStatus)));
assert.ok(yorkRecords.every((record) => !record.productionPresent && !record.localPresent));

for (const [packetId, count] of [
  ["research-completion-pa-york-01", 7],
  ["research-completion-pa-brogue-01", 1],
]) {
  const packet = packets.packets.find((entry) => entry.id === packetId);
  assert.ok(packet, `Missing generated packet ${packetId}`);
  assert.equal(packet.count, count);
  assert.equal(packet.status, "submitted");
  const claim = claims.claims.find((entry) => entry.packetId === packetId);
  assert.ok(claim, `Missing claim for ${packetId}`);
  assert.equal(claim.status, "submitted");
  assert.equal(claim.issueUrl, "https://github.com/Buildrbear/auditmap/issues/74");
  assert.equal(claim.pullRequestUrl, "https://github.com/Buildrbear/auditmap/pull/75");
}

const capacity = queue.activeCluster.resumeCheckpoint.campaignCapacity;
assert.equal(capacity.asOf, "2026-09-04");
assert.equal(capacity.activeLanes.municipalityBreadth.length, 2);
assert.equal(capacity.available.municipalityBreadth, 0);

const nixon = intake.records.find((record) => record.slug === "richard-m-nixon-park");
assert.match(nixon.freshness, /reopening supersedes the older closure alert/);
const penn = intake.reviewQueue.find((item) => item.park_slug === "penn-park");
assert.match(penn.recommended_next_action, /seasonal subsite/);
const railTrail = intake.reviewQueue.find((item) => item.park_slug === "heritage-rail-trail-county-park");
assert.match(railTrail.recommended_next_action, /exact downtown trail entrance/);

console.log("York, PA anchor-park inventory verification passed: 8 unpublished parents, 2 generated research packets.");
