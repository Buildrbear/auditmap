#!/usr/bin/env node

const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const readJson = (file) => JSON.parse(fs.readFileSync(path.join(root, file), "utf8"));

const intake = readJson("data/research-intake/mesa-public-parks-2026-08-20.json");
const ledger = readJson("data/release-ledgers/mesa-public-parks-2026-08-20.json");
const spatial = readJson("data/spatial-source-registry.json");
const claims = readJson("data/national-work-packet-claims.json");
const packets = readJson("data/generated/national-work-packets.json");
const sitemap = fs.readFileSync(path.join(root, "sitemap.xml"), "utf8");

assert.equal(intake.campaignId, "mesa-public-parks-2026-08-20");
assert.equal(intake.contributionTier, "inventory");
assert.equal(intake.records.length, 25);
assert.equal(intake.selection.candidateCount, 26);
assert.equal(intake.selection.acceptedCount, 25);
assert.equal(intake.selection.excluded.length, 1);
assert.equal(intake.selection.excluded[0].name, "Hohokam Stadium");
assert.match(intake.sourcePolicy.imageRights, /No City images are imported/);
assert.match(intake.sourcePolicy.spatialReview, /not copied or redistributed/);

const slugs = new Set();
const sourceIds = new Set();
for (const record of intake.records) {
  assert.equal(record.city, "Mesa");
  assert.equal(record.state, "AZ");
  assert.equal(record.managing_agency, "City of Mesa Parks, Recreation and Community Facilities");
  assert.equal(record.duplicate_status, "accepted-net-new-parent");
  assert.equal(record.contribution_status, "qualified-inventory-parent");
  assert.ok(Number.isFinite(record.latitude));
  assert.ok(Number.isFinite(record.longitude));
  assert.ok(record.latitude > 33.2 && record.latitude < 33.6);
  assert.ok(record.longitude > -112 && record.longitude < -111.5);
  assert.match(record.official_source_url, /^https:\/\/www\.mesaaz\.gov\//);
  assert.match(record.official_record_id, /^PKPK\d+$/);
  assert.ok(record.sources.length >= 2);
  assert.ok(record.sources.every((source) => source.checkedAt === "2026-08-20"));
  assert.ok(!slugs.has(record.slug), `Duplicate Mesa slug: ${record.slug}`);
  assert.ok(!sourceIds.has(record.official_record_id), `Duplicate Mesa source ID: ${record.official_record_id}`);
  slugs.add(record.slug);
  sourceIds.add(record.official_record_id);

  const route = `/us/az/mesa/parks/${record.slug.replace(/^mesa-/, "")}`;
  assert.ok(!sitemap.includes(`<loc>https://www.auditmap.org${route}</loc>`), `${route} must remain unpublished`);
}

const reconciled = intake.records.filter((record) => record.coordinate_reconciliation);
assert.equal(reconciled.length, 4);
assert.deepEqual(
  reconciled.map((record) => record.name).sort(),
  ["Eagles Park", "Fitch Park", "Kleinman Park", "Sherwood Park"],
);
for (const record of reconciled) {
  assert.equal(record.position_quality, "reviewed-named-osm-park-geometry");
  assert.equal(record.coordinate_reconciliation.status, "resolved-city-page-pin-outside-official-boundary");
  assert.match(record.coordinate_reconciliation.publication_rule, /recheck before launch-guide publication/);
}

const brady = intake.records.find((record) => record.name === "Christopher J. Brady Park");
assert.ok(brady);
assert.deepEqual(brady.aliases, ["Monterey Park", "Monterey"]);
assert.equal(brady.official_record_id, "PKPK35");

assert.equal(ledger.summary.intakeRecords, 25);
assert.equal(ledger.summary.needsLaunchGuide, 25);
assert.equal(ledger.summary.generatedLocally, 0);
assert.equal(ledger.summary.deployed, 0);
assert.ok(ledger.records.every((record) => record.state === "needs-launch-guide"));

const mesaSpatial = spatial.sources.find(
  (source) => source.id === "mesa-facility-directory-data-and-park-boundaries",
);
assert.ok(mesaSpatial, "Missing registered Mesa official source set");
assert.match(mesaSpatial.licenseStatus, /redistribution-restricted/);
assert.ok(mesaSpatial.prohibitedUntilApproved.some((rule) => /bulk public redistribution/.test(rule)));

const claim = claims.claims.find((entry) => entry.packetId === "research-completion-az-mesa-01");
assert.ok(claim, "Mesa packet claim is missing");
assert.ok(["claimed", "submitted"].includes(claim.status));
assert.equal(claim.issueUrl, "https://github.com/Buildrbear/auditmap/issues/49");

const packet = packets.packets.find((entry) => entry.id === "research-completion-az-mesa-01");
assert.ok(packet, "Generated Mesa packet is missing");
assert.equal(packet.count, 25);
assert.ok(["claimed", "submitted"].includes(packet.status));

assert.ok(!fs.existsSync(path.join(root, "us/az/mesa")), "Mesa pages must not be generated by this inventory packet");

console.log("Mesa parks catalogue-breadth verification passed.");
