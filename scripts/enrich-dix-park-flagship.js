function localImagePath(item, asset, index) {
  if (asset.remote.startsWith("/")) return asset.remote;
  const suffix = asset.name || (index === 0 ? "hero" : `photo-${index + 1}`);
  return `/assets/parks/dix-park/flagship/${item.slug}/${suffix}.webp`;
}

